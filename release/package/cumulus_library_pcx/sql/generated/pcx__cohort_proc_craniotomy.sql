CREATE TABLE pcx__cohort_proc_craniotomy AS 
SELECT DISTINCT * FROM 
 pcx__cohort_study_population_proc , 
pcx__valueset_proc_craniotomy
WHERE
pcx__cohort_study_population_proc.proc_code = pcx__valueset_proc_craniotomy.code and 
pcx__cohort_study_population_proc.proc_system = pcx__valueset_proc_craniotomy.system