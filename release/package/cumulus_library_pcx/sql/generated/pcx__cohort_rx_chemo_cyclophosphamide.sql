CREATE TABLE pcx__cohort_rx_chemo_cyclophosphamide AS 
SELECT DISTINCT * FROM 
 pcx__cohort_study_population_rx , 
pcx__valueset_rx_chemo_cyclophosphamide
WHERE
pcx__cohort_study_population_rx.rx_code = pcx__valueset_rx_chemo_cyclophosphamide.code and 
pcx__cohort_study_population_rx.rx_system = pcx__valueset_rx_chemo_cyclophosphamide.system